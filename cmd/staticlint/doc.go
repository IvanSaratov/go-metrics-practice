// Команда staticlint запускает набор статических анализаторов для Go-кода.
// Multichecker загружает пакеты, выполняет проверки и выводит замечания.
//
// # Запуск
//
// Из корня проекта можно проверить все пакеты, включая тестовые файлы:
//
//	go run ./cmd/staticlint ./...
//
// Вместо ./... можно указать отдельный пакет. При успехе код завершения — 0,
// при замечаниях или ошибке запуска — ненулевой. Замечания содержат файл и строку.
//
// Для запуска через go vet нужно сначала собрать бинарник:
//
//	mkdir -p bin
//	go build -o ./bin/staticlint ./cmd/staticlint
//	go vet -vettool=./bin/staticlint ./...
//
// Список проверок и справка по отдельному анализатору:
//
//	go run ./cmd/staticlint help
//	go run ./cmd/staticlint help noosexit
//
// По умолчанию включены все проверки. Флаг -noosexit оставляет только noosexit,
// а -S1002=false отключает S1002. Флаги указываются перед списком пакетов.
//
// # Стандартные анализаторы
//
// Подключены 35 проверок из golang.org/x/tools/go/analysis/passes:
//
//   - appends: вызов append без добавляемых элементов.
//   - asmdecl: несоответствие ассемблерного кода объявлениям Go.
//   - assign: бесполезные присваивания, например присваивание переменной самой себе.
//   - atomic: ошибки при использовании операций sync/atomic.
//   - bools: подозрительные сочетания логических условий.
//   - buildtag: ошибки в ограничениях сборки go:build и +build.
//   - cgocall: нарушения правил передачи указателей между Go и C.
//   - composites: литералы структур из других пакетов без имён полей.
//   - copylocks: копирование значений, содержащих блокировки.
//   - defers: вычисление time.Since сразу при регистрации defer вместо завершения функции.
//   - directive: некорректные директивы инструментов Go, например go:debug.
//   - errorsas: неподходящий аргумент назначения в errors.As.
//   - framepointer: изменение указателя кадра в ассемблере до его сохранения.
//   - hostport: неправильная сборка сетевого адреса, в том числе для IPv6.
//   - httpresponse: обращение к HTTP-ответу до проверки ошибки запроса.
//   - ifaceassert: утверждения типа между несовместимыми интерфейсами.
//   - loopclosure: опасный захват переменной цикла вложенной функцией с учётом версии Go.
//   - lostcancel: отсутствие вызова функции отмены созданного контекста.
//   - nilfunc: бессмысленное сравнение объявленной функции с nil.
//   - printf: несоответствие строки форматирования аргументам Printf-подобных функций.
//   - shift: сдвиг на число бит, не меньшее разрядности значения.
//   - sigchanyzer: небуферизованный канал в signal.Notify.
//   - slog: неверные пары ключей и значений в структурированных логах.
//   - stdmethods: неверные сигнатуры методов с известным назначением, например ReadByte.
//   - stdversion: использование стандартного API, недоступного выбранной версии Go.
//   - stringintconv: подозрительное преобразование числа в строку как в один символ.
//   - structtag: неверный формат тегов полей структуры.
//   - testinggoroutine: вызов Fatal и похожих методов из посторонней горутины теста.
//   - tests: ошибки в объявлениях тестов, бенчмарков и примеров.
//   - timeformat: перепутанные месяц и день в шаблоне времени 2006-02-01.
//   - unmarshal: передача неподходящего значения вместо указателя при декодировании.
//   - unreachable: недостижимый код.
//   - unsafeptr: подозрительные преобразования uintptr в unsafe.Pointer.
//   - unusedresult: игнорирование результата функций, для которых это обычно ошибка.
//   - waitgroup: неверное использование sync.WaitGroup, например Add внутри новой горутины.
//
